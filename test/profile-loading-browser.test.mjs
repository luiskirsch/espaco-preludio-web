 assert.equal(await ev('document.getElementById("mfaItem").getAttribute("aria-busy")'),'true');
 await ev('document.getElementById("mfaItem").click()');assert.equal(await ev('window.mfaActions||0'),0);
 await ev('window.resolveMfa({required:true,enabled:true})');
